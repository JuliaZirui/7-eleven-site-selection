"""Raw-state summaries for the analyst's manual scan of the generalisation
stations (plan_llm_data_audit.md, generalisation protocol).

One Markdown file per station with what the analyst looked at for the
candidate sites, in the raw (corrections-off) state: the largest IHK
registrations, the visitor estimates of the gateway attractions, the full
competitor list, and the largest buildings. Built from the same inputs as
the worklists (audit_candidates.reference_context), but it shows data
only: no worklist flags and nothing from the auditor, so the scan stays
independent of both.

    python3 src/audit_scan_sheet.py

writes comparison/audit_manual_scans/<station>_raw_summary.md. Offline:
every input is already stored.
"""

from __future__ import annotations

import json
from pathlib import Path

import audit_candidates as ac
import audit_eval
from demand_model import annual_visitors, employees_estimate, latest_visitor_fit
from geo import haversine_m

PROJECT_ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = PROJECT_ROOT / "comparison" / "audit_manual_scans"

MIN_EMPLOYEES = 50  # registrations listed: size-class floor at or above this
TOP_BUILDINGS = 25
NAME_HINTS = 3  # nearest named OSM objects within 40 m of a registration


def _osm(ref: str) -> str:
    return f"[{ref}](https://www.openstreetmap.org/{ref})"


def _map(lat: float, lon: float) -> str:
    return f"[{lat:.5f}, {lon:.5f}](https://www.openstreetmap.org/?mlat={lat:.6f}&mlon={lon:.6f}#map=19/{lat:.6f}/{lon:.6f})"


def _cell(text) -> str:
    return str(text if text not in (None, "") else "—").replace("|", "/").replace("\n", " ")


def summary(station: dict, fit: dict, fit_name: str) -> str:
    ctx = ac.reference_context(station)
    proj = ac._Projector(ctx.lat, ctx.lon)
    places = ac._places(ctx, proj)
    from shapely.geometry import Point

    regs = [(r, employees_estimate(r.get("employees_range"))) for r in ctx.registrations]
    workers = sum(v for _, v in regs if v)
    unknown = sum(1 for _, v in regs if v is None)
    visitors = sorted(((r, annual_visitors(r["pageviews"], fit)) for r in ctx.visitor_records
                       if r.get("pageviews") is not None), key=lambda x: -x[1] * x[0]["share"])
    visitors_day = sum(a * r["share"] / 365 for r, a in visitors)
    residents = station.get("residents")

    L = [
        f"# Manual scan — {ctx.name} (raw state)",
        "",
        f"Station point {_map(ctx.lat, ctx.lon)}, 400 m circle. Generated by `python3 src/audit_scan_sheet.py`. "
        "Raw state: every IHK registration at its size-class midpoint, every visitor figure from the pageview "
        "conversion, competitors conflated without quality rules or verified corrections. Data only: nothing here "
        "comes from the auditor or from the audit worklist.",
        "",
        "**Protocol:** at most 20 minutes, before opening any audit output for this station. Look for the five "
        "issue types (fame vs attendance, company-wide headcount at one address, missing large employer or venue, "
        "competitor category error, duplicate competitor), with the same sources as the original checks. Write "
        "the findings in the table at the end.",
        "",
        "## Demand in the raw state",
        "",
        "| Segment | People per day | Basis |",
        "| --- | --- | --- |",
        f"| Residents | {residents:,.0f} | area-weighted MSS 2025 (reference-station calibration) |" if residents
        else "| Residents | — | not available |",
        f"| Workers | {workers:,.0f} | {len(regs)} IHK registrations in the circle at size-class midpoints "
        f"({unknown} of unknown size left out) |",
        f"| Visitors | {visitors_day:,.0f} | {len(visitors)} gateway attractions with a Wikipedia article, "
        f"pageviews → visitors ({fit_name}), times the station's 1/k share, / 365 |",
        "",
        f"## IHK registrations with a size class of {MIN_EMPLOYEES} or more",
        "",
        "IHK data are anonymised; the OSM names within 40 m are the identification hint.",
        "",
        "| # | opendata_id | Size class | Counted as | Industry (NACE) | Registration age (years) | Type | "
        "Point | OSM names within 40 m |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    large = sorted([(r, v) for r, v in regs if (ac._class_floor(r.get("employees_range")) or 0) >= MIN_EMPLOYEES],
                   key=lambda x: -(x[1] or 0))
    for i, (r, v) in enumerate(large, 1):
        pt = Point(proj.xy(r["lat"], r["lon"]))
        near = sorted(((p, p.geom.distance(pt)) for p in places if p.tags.get("name")), key=lambda x: x[1])
        hints = "; ".join(f"{p.tags['name']} ({d:.0f} m)" for p, d in near if d <= ac.NAME_HINT_M)
        hints = "; ".join(hints.split("; ")[:NAME_HINTS]) if hints else ""
        L.append(f"| {i} | {r.get('opendata_id')} | {_cell(r.get('employees_range'))} | {v:,.0f} | "
                 f"{_cell(r.get('nace_desc'))} | {_cell(r.get('business_age'))} | {_cell(r.get('business_type'))} | "
                 f"{_map(r['lat'], r['lon'])} | {_cell(hints)} |")
    if not large:
        L.append("| — | none | | | | | | | |")

    L += ["", "## Gateway attractions, highest visitor estimate first", "",
          f"Gateway station: {ctx.provenance.get('gateway_station') or ctx.provenance.get('gtfs_station') or '—'}. "
          "Venues up to 2 km away count, weighted by the station's share 1/k (k = stations the venue is nearest to).",
          "",
          "| # | Attraction | Kind | Distance (m) | Pageviews (12 m) | Visitors/yr (conversion) | Share 1/k | "
          "Visitors/day here | Wikipedia (de) |",
          "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for i, (r, a) in enumerate(visitors, 1):
        title = (r.get("wikipedia_titles") or {}).get("dewiki")
        L.append(f"| {i} | {_cell(r.get('name'))} | {_cell(r.get('kind'))} | {r.get('distance_m', 0):,.0f} | "
                 f"{r['pageviews']:,} | {a:,.0f} | {r['share']:.2f} | {a * r['share'] / 365:,.0f} | {_cell(title)} |")
    no_article = sum(1 for r in ctx.visitor_records if r.get("pageviews") is None)
    if no_article:
        L.append(f"\n{no_article} further gateway attractions have no Wikipedia article and count 0.")

    comps = sorted(ctx.competitors, key=lambda c: (c["category"], c["name"] or ""))
    L += ["", f"## Competitors ({len(comps)}, raw conflation)", "",
          "| # | Name | Category | Providers | Source records (source: name [category]) | Distance (m) | "
          "Opening hours (OSM) | Point |",
          "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for i, c in enumerate(comps, 1):
        members = "; ".join(f"{m['source'].split('_')[0]}: {m['name']} [{m['category']}]" for m in c["payload"]["members"])
        L.append(f"| {i} | {_cell(c['name'])} | {c['category']} | {', '.join(c['payload']['providers'])} | "
                 f"{_cell(members)} | {haversine_m(ctx.lat, ctx.lon, c['lat'], c['lon']):,.0f} | "
                 f"{_cell(c.get('opening_hours_raw'))} | {_map(c['lat'], c['lon'])} |")

    blds = []
    for p in places:
        footprint, floor, levels_tagged = ac._floor_area(p)
        c = p.geom.centroid
        if floor is None or c.distance(Point(0, 0)) > ctx.radius_m:
            continue
        blds.append((p, footprint, floor, levels_tagged))
    blds.sort(key=lambda x: -x[2])
    L += ["", f"## Largest buildings in the circle (top {TOP_BUILDINGS} by floor area)", "",
          "Floor area = footprint × `building:levels`; without a levels tag the footprint alone (a lower bound).",
          "",
          "| # | OSM | Name | Building | Levels | Footprint (m²) | Floor area (m²) | Address | Other tags |",
          "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for i, (p, fp, fa, lt) in enumerate(blds[:TOP_BUILDINGS], 1):
        other = ", ".join(f"{k}={p.tags[k]}" for k in ("office", "government", "diplomatic", "amenity", "shop",
                                                       "operator", "company", "tourism") if k in p.tags)
        L.append(f"| {i} | {_osm(p.ref)} | {_cell(p.tags.get('name'))} | {_cell(p.tags.get('building'))} | "
                 f"{_cell(p.tags.get('building:levels'))} | {fp:,.0f} | {fa:,.0f}{'' if lt else ' (lower bound)'} | "
                 f"{_cell(ac._address(p.tags))} | {_cell(other)} |")

    L += ["", "## Scan record (fill in)", "",
          "- Analyst:",
          "- Date and start time:",
          "- Minutes used (max 20):",
          "- Sources used:",
          "",
          "| # | Record (id / name) | Issue type | What is wrong, and the evidence | Estimated correct value |",
          "| --- | --- | --- | --- | --- |",
          "| 1 | | | | |",
          ""]
    return "\n".join(L)


def run() -> list[Path]:
    fit, fit_path = latest_visitor_fit()
    anchors = {s["station"]: s for s in json.loads(audit_eval.DRAW_ANCHORS.read_text())["stations"]}
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    out = []
    for name in audit_eval.AUDIT_SETS["generalisation"]:
        path = OUT_DIR / f"{ac._key(name)}_raw_summary.md"
        path.write_text(summary(anchors[name], fit, fit_path.name), encoding="utf-8")
        out.append(path)
        print(path.relative_to(PROJECT_ROOT))
    return out


if __name__ == "__main__":
    run()
